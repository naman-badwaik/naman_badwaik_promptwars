import { DecisionInput, BlindSpotAnalysis } from "./schemas";

export interface DossierOptions {
  generatedAt?: string;
}

/**
 * Generates a clean, deterministic, portable Markdown document
 * combining the user's initial decision dilemma, the AI blind spot analysis,
 * and the user's personal reflections.
 */
export function generateDossierMarkdown(
  input: DecisionInput,
  analysis: BlindSpotAnalysis,
  reflections: Record<number, string> = {},
  options: DossierOptions = {}
): string {
  const dateStr = options.generatedAt || new Date().toISOString().split("T")[0];

  const sections: string[] = [];

  // Header & Disclaimer
  sections.push(
    `# BLINDSPOT AI — DECISION DOSSIER`,
    `> **Date:** ${dateStr}  \n> **Notice:** This dossier is a thinking companion and reflection log. BlindSpot AI does not make the decision for you. The final choice remains entirely yours.\n`
  );

  // 1. Original Dilemma Frame
  sections.push(
    `## 1. THE DECISION DILEMMA`,
    `### Core Decision`,
    input.decision,
    ``,
    `### Current Leaning / Instinct`,
    input.currentThinking,
    ``,
    `### Relevant Context & Background`,
    input.context,
    ``,
    input.constraints
      ? `### Constraints, Fears & Priorities\n${input.constraints}\n`
      : `### Constraints, Fears & Priorities\n*(None explicitly specified)*\n`
  );

  // 2. Reversibility
  sections.push(
    `## 2. REVERSIBILITY CLASSIFICATION`,
    `**Framework:** ${analysis.reversibility.type}`,
    ``,
    `**Strategic Rationale:**`,
    analysis.reversibility.rationale,
    ``
  );

  // 3. What You May Be Missing
  sections.push(
    `## 3. WHAT YOU MAY BE MISSING`,
    ...analysis.whatYouMayBeMissing.map(
      (item, idx) =>
        `### ${idx + 1}. ${item.title} [${item.blindSpotCategory}]\n${item.description}\n`
    )
  );

  // 4. Assumptions Being Made
  sections.push(
    `## 4. UNEXAMINED ASSUMPTIONS`,
    ...analysis.assumptionsBeingMade.map(
      (item, idx) =>
        `### Assumption ${idx + 1}\n- **Stated or Implied Premise:** "${item.statedOrImpliedAssumption}"\n- **Counter-Evidence & Reality Check:** ${item.counterEvidenceCheck}\n`
    )
  );

  // 5. Risks & Hidden Trade-offs
  sections.push(
    `## 5. RISKS & ASYMMETRIC TRADE-OFFS`,
    ...analysis.risksAndTradeoffs.map(
      (item, idx) =>
        `### Risk ${idx + 1}: ${item.riskOrHiddenCost}\n- **Worst-Case Downside:** ${item.worstCaseScenario}\n- **Mitigation Strategy:** ${item.mitigationIdea}\n`
    )
  );

  // 6. Alternative Perspectives
  sections.push(
    `## 6. ALTERNATIVE PERSPECTIVES & LENSES`,
    ...analysis.alternativePerspectives.map(
      (item, idx) =>
        `### Lens ${idx + 1}: ${item.viewpointLens}\n${item.howTheyViewThis}\n`
    )
  );

  // 7. Catalytic Questions & User Reflections
  sections.push(
    `## 7. CATALYTIC QUESTIONS & PERSONAL REFLECTIONS`,
    ...analysis.catalyticQuestions.map((item, idx) => {
      const userNote = reflections[idx]?.trim();
      const reflectionText = userNote
        ? userNote
        : `*(No personal reflection recorded yet)*`;

      return `### Question ${idx + 1}: "${item.question}"\n- **Why this probe matters:** ${item.whyThisMatters}\n- **Your Reflection:**\n  > ${reflectionText.replace(/\n/g, "\n  > ")}\n`;
    })
  );

  // 8. Mind-Shift Triggers
  sections.push(
    `## 8. MIND-SHIFT TRIGGERS (CONDITIONS TO PIVOT)`,
    `Revisit your preferred direction if any of the following occur:`,
    ``,
    ...analysis.mindShiftTriggers.map((trigger, idx) => `${idx + 1}. ${trigger}`)
  );

  // Concluding Epistemic Seal
  sections.push(
    `---`,
    `*Generated by BlindSpot AI — An epistemic thinking companion designed to spot what is overlooked. Your decision stays yours.*`
  );

  return sections.join("\n");
}
